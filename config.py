"""
config.py — читаем настройки бота из файла .env

Зачем отдельный файл:
Секретные вещи (токен бота, ключи API) НЕЛЬЗЯ писать прямо в коде,
иначе они попадут в git и их увидят все. Поэтому мы держим их в файле .env
(он в .gitignore и не попадёт в репозиторий), а здесь просто их читаем.

Библиотека python-dotenv умеет прочитать .env и положить значения
в "переменные окружения", откуда мы их достаём через os.getenv(...).
"""

import os
from dotenv import load_dotenv

# Загружаем переменные из файла .env в окружение процесса.
# Если .env нет — ничего страшного не упадёт, просто значения будут пустыми.
load_dotenv()

# Токен бота от @BotFather. Без него бот не запустится — это главный ключ.
BOT_TOKEN = os.getenv("BOT_TOKEN", "")

# Твой личный Telegram user_id (число). Бот будет отвечать только тебе.
# 0 означает "не задан" — тогда бот отвечает всем (удобно для теста).
OWNER_USER_ID = int(os.getenv("OWNER_USER_ID", "0"))

# (необязательно) Ключ DeepL. Если он задан — используем DeepL для перевода,
# если пусто — используем бесплатный Google Translate через deep-translator.
DEEPL_API_KEY = os.getenv("DEEPL_API_KEY", "").strip()

# Как часто (в минутах) планировщик заглядывает в базу и проверяет,
# нет ли слов, которым пора на повторение. 5 минут — разумный старт.
CHECK_INTERVAL_MINUTES = int(os.getenv("CHECK_INTERVAL_MINUTES", "5"))

# Имя файла базы данных SQLite. Это просто один файл на диске.
DB_PATH = os.getenv("DB_PATH", "words.db")


def validate() -> None:
    """
    Простая проверка при старте: если нет токена — сразу понятная ошибка,
    а не загадочный сбой где-то в глубине.
    """
    if not BOT_TOKEN:
        raise RuntimeError(
            "BOT_TOKEN не задан! Скопируй .env.example в .env и впиши туда токен от @BotFather."
        )

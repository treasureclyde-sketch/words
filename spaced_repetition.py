"""
spaced_repetition.py — логика "интервального повторения" (spaced repetition).

Идея простая и научно обоснованная: то, что ты только что выучил, надо
повторить скоро. Если вспомнил — можно повторить попозже. И так интервалы
растут: 1 час → 1 день → 3 дня → 7 дней → 14 дней. Слова, которые ты знаешь,
почти не дёргают тебя, а трудные (где ты ошибаешься) возвращаются часто.

У каждого слова есть "уровень" (level): 0, 1, 2, 3, 4, 5.
- Ответил ВЕРНО  → уровень +1, следующий показ через больший интервал.
- Ответил НЕВЕРНО → уровень сбрасывается в 0, показать снова скоро.
- Дошёл до максимального уровня → слово считается "выучено".
"""

from datetime import timedelta

# Интервалы для уровней 0..4.
# level 0 → ждём 1 час, level 1 → 1 день, level 2 → 3 дня, и т.д.
# Индекс в списке = текущий уровень слова.
INTERVALS = [
    timedelta(hours=1),   # уровень 0
    timedelta(days=1),    # уровень 1
    timedelta(days=3),    # уровень 2
    timedelta(days=7),    # уровень 3
    timedelta(days=14),   # уровень 4
]

# Максимальный уровень. Если слово дошло до него — оно "выучено"
# и больше не участвует в случайных проверках.
MAX_LEVEL = len(INTERVALS)  # = 5


def next_interval(level: int) -> timedelta:
    """
    Возвращает, через сколько времени показать слово при данном уровне.
    Если уровень выше списка — берём последний (самый длинный) интервал.
    """
    if level < 0:
        level = 0
    if level >= len(INTERVALS):
        return INTERVALS[-1]
    return INTERVALS[level]


def apply_correct(level: int) -> int:
    """Ответ верный → поднимаем уровень на 1, но не выше MAX_LEVEL."""
    return min(level + 1, MAX_LEVEL)


def apply_wrong(level: int) -> int:
    """Ответ неверный → сбрасываем уровень в 0 (учим заново)."""
    return 0


def is_learned(level: int) -> bool:
    """Слово выучено, если добралось до максимального уровня."""
    return level >= MAX_LEVEL
